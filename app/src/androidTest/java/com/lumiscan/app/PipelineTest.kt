    @Test
    fun edgeDetection_idCardKeepsItsWholeEdge() {
        // Corners where the card's straight sides meet (the card has rounded corners), as placed by
        // tools/testdata/make_card_photos.py: on a dark wooden desk and on a light, low-contrast one.
        val cards = mapOf(
            "card_dark.jpg" to listOf(190f to 820f, 1640f to 900f, 1590f to 1830f, 150f to 1730f),
            "card_light.jpg" to listOf(130f to 900f, 1660f to 860f, 1700f to 1840f, 170f to 1820f),
        )
        for ((name, truth) in cards) {
            val q = EdgeDetector.detect(asset(name), card = true, foldTrim = false)
            assertNotNull("$name: outline should be found", q)
            val p = q!!.points
            // Signed distance of the card's corners beyond each side (outwards positive): the whole
            // card is inside the outline, with a thin margin.
            val beyond = (0 until 4).map { k ->
                val a = p[k]; val b = p[(k + 1) % 4]
                val len = kotlin.math.hypot(b.x - a.x, b.y - a.y)
                truth.maxOf { (x, y) -> ((x - a.x) * (b.y - a.y) - (y - a.y) * (b.x - a.x)) / len }
            }
            android.util.Log.i("PipelineTest", "$name card=$q beyond=$beyond old=${EdgeDetector.detect(asset(name))}")
            beyond.forEachIndexed { k, d -> assertTrue("$name: side $k cuts the card by $d px", d < -3f) }
            p.zip(truth).forEach { (c, t) -> assertTrue("$name: corner $c vs $t", kotlin.math.hypot(c.x - t.first, c.y - t.second) < 45f) }
        }
    }

