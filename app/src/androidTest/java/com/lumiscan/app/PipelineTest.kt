    @Test
    fun pdfTools_roundTrip() {
        val img = assetFile("doc_flat.jpg")
        val a = PdfTools.fromImages(listOf(img, img, img), File(dir, "a.pdf"))
        assertEquals(3, PdfTools.pageCount(a))
        val merged = PdfTools.merge(listOf(a, a), File(dir, "m.pdf"))
        assertEquals(6, PdfTools.pageCount(merged))
        val parts = PdfTools.split(merged, listOf(0..1, 2..5), dir, "s")
        assertEquals(listOf(2, 4), parts.map { PdfTools.pageCount(it) })
        assertEquals(2, PdfTools.pageCount(PdfTools.extract(merged, listOf(5, 0), File(dir, "e.pdf"))))
        assertEquals(4, PdfTools.pageCount(PdfTools.deletePages(merged, setOf(1, 2), File(dir, "d.pdf"))))
        PdfTools.rotatePages(a, setOf(0), 90, File(dir, "r.pdf"))

        val enc = PdfTools.encrypt(a, "pw", File(dir, "enc.pdf"))
        assertTrue(PdfTools.isEncrypted(enc))
        assertEquals(3, PdfTools.pageCount(enc, "pw"))
        val dec = PdfTools.decrypt(enc, "pw", File(dir, "dec.pdf"))
        assertFalse(PdfTools.isEncrypted(dec))

        val wm = PdfTools.watermark(a, "TEST", 80, Color.GRAY, 1f, File(dir, "wm.pdf"))
        val small = PdfTools.compress(a, 1100, 55, File(dir, "c.pdf"))
        assertTrue("compressed ${small.length()} < ${a.length()}", small.length() < a.length())
        val sig = Bitmap.createBitmap(200, 80, Bitmap.Config.ARGB_8888).apply { eraseColor(Color.BLUE) }
        val signed = PdfTools.stamp(a, 0, sig, 0.6f, 0.8f, 0.3f, 0.1f, File(dir, "sig.pdf"))

        // Rendering works for every produced file; the stamp is blue at its spot.
        for (f in listOf(merged, dec, wm, small, signed)) PdfPages(f).use { assertTrue(it.render(0, 400).width == 400) }
        PdfPages(signed).use { p ->
            val b = p.render(0, 1000)
            val c = b.getPixel((0.75f * b.width).toInt(), (0.85f * b.height).toInt())
            assertTrue("stamp colour ${Integer.toHexString(c)}", Color.blue(c) > 200 && Color.red(c) < 60)
        }
    }

    @Test
    fun imageTools_removeInkAndWatermark() {
        val flat = asset("doc_flat.jpg")
        val clean = ImageTools.removeHandwriting(flat, HandwritingOptions())
        // The blue signature curve passes through ~(341, 1097); it becomes paper white.
        assertTrue(Color.blue(flat.getPixel(341, 1097)) > Color.red(flat.getPixel(341, 1097)) + 60)
        val p = clean.getPixel(341, 1097)
        assertTrue("ink left: ${Integer.toHexString(p)}", Color.red(p) > 230 && Color.blue(p) > 230)
        val noWm = ImageTools.removeDocWatermark(flat, 185)
        // Pale grey watermark pixels in its area: many before, (almost) none after.
        fun grey(b: Bitmap) = (1300 until 1600 step 2).sumOf { y ->
            (300 until 940 step 2).count { x -> val c = b.getPixel(x, y); Color.red(c) in 150..235 && abs(Color.red(c) - Color.blue(c)) < 12 }
        }
        val before = grey(flat); val after = grey(noWm)
        assertTrue("watermark pixels $before -> $after", before > 500 && after < before / 20)
        // Body text survives.
        val dark = (0 until noWm.width).count { x -> Color.red(noWm.getPixel(x, 215)) < 100 }
        assertTrue(dark > 50)
    }

