    @Test
    fun signature_extractedFromPhotoOfPaper() {
        // Off-white, unevenly lit paper with a dark blue signature stroke.
        val photo = Bitmap.createBitmap(900, 500, Bitmap.Config.ARGB_8888)
        val c = android.graphics.Canvas(photo)
        c.drawPaint(android.graphics.Paint().apply {
            shader = android.graphics.LinearGradient(0f, 0f, 900f, 500f, Color.rgb(235, 232, 225), Color.rgb(190, 186, 178), android.graphics.Shader.TileMode.CLAMP)
        })
        val ink = android.graphics.Paint(android.graphics.Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(25, 40, 120); style = android.graphics.Paint.Style.STROKE; strokeWidth = 9f; strokeCap = android.graphics.Paint.Cap.ROUND
        }
        val path = android.graphics.Path().apply { moveTo(200f, 300f); cubicTo(300f, 120f, 420f, 420f, 520f, 220f); lineTo(700f, 260f) }
        c.drawPath(path, ink)
        val sig = ImageTools.extractSignature(photo)
        assertNotNull(sig)
        // Cropped to the ink, transparent paper, opaque ink.
        assertTrue("size ${sig!!.width}x${sig.height}", sig.width in 450..620 && sig.height in 100..320)
        assertEquals(0, Color.alpha(sig.getPixel(2, 2)))
        val opaque = (0 until sig.width).sumOf { x -> (0 until sig.height).count { y -> Color.alpha(sig.getPixel(x, y)) > 200 } }
        assertTrue("ink pixels $opaque", opaque > 1500)
        // Blank paper yields nothing.
        val blank = ImageTools.extractSignature(Bitmap.createBitmap(400, 300, Bitmap.Config.ARGB_8888).apply { eraseColor(Color.rgb(230, 228, 220)) })
        assertNull("blank paper gave ${blank?.width}x${blank?.height}", blank)
    }
