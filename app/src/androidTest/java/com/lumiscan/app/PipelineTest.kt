    @Test
    fun edgeDetection_findsPhotographedPage_andIgnoresFlatPage() {
        val photo = asset("doc_photo.jpg")
        val q = EdgeDetector.detect(photo)
        assertNotNull("page outline should be found", q)
        // Ground truth corners of the synthetic photo (top-left origin), ±25px.
        val expected = listOf(253f to 157f, 1362.5f to 315.5f, 1095.5f to 1585.9f, 223.4f to 1588.4f)
        q!!.points.zip(expected).forEach { (p, e) ->
            assertTrue("corner $p vs $e", abs(p.x - e.first) < 25 && abs(p.y - e.second) < 25)
        }
        assertNull("a flat page must not be cropped to its table", EdgeDetector.detect(asset("doc_flat.jpg")))
    }

    /** Points of the unit square (spread coordinates) projected into a photo with these corners. */
    private fun project(corners: List<Pair<Float, Float>>, pts: List<Pair<Double, Double>>): List<Pair<Float, Float>> {
        val unit = org.opencv.core.MatOfPoint2f(org.opencv.core.Point(0.0, 0.0), org.opencv.core.Point(1.0, 0.0), org.opencv.core.Point(1.0, 1.0), org.opencv.core.Point(0.0, 1.0))
        val dst = org.opencv.core.MatOfPoint2f(*corners.map { org.opencv.core.Point(it.first.toDouble(), it.second.toDouble()) }.toTypedArray())
        val m = org.opencv.imgproc.Imgproc.getPerspectiveTransform(unit, dst)
        val out = org.opencv.core.MatOfPoint2f()
        org.opencv.core.Core.perspectiveTransform(org.opencv.core.MatOfPoint2f(*pts.map { org.opencv.core.Point(it.first, it.second) }.toTypedArray()), out, m)
        return out.toArray().map { it.x.toFloat() to it.y.toFloat() }
    }

    private fun assertCorners(q: com.lumiscan.app.imaging.Quad?, expected: List<Pair<Float, Float>>, what: String) {
        assertNotNull("$what: outline should be found", q)
        q!!.points.zip(expected).forEach { (p, e) ->
            assertTrue("$what: corner $p vs $e", abs(p.x - e.first) < 25 && abs(p.y - e.second) < 25)
        }
    }

    @Test
    fun edgeDetection_openBooklet() {
        // Spread corners as placed by tools/testdata/make_book_photos.swift; the fold is its centre line.
        val clipped = listOf(110f to 330f, 1890f to 420f, 1860f to 1470f, 40f to 1420f)
        val (foldTop, foldBottom) = project(clipped, listOf(0.5 to 0.0, 0.5 to 1.0))
        // Facing page runs off the frame → the outline stops at the fold, not at the frame edge.
        assertCorners(EdgeDetector.detect(asset("book_clipped.jpg")), listOf(clipped[0], foldTop, foldBottom, clipped[3]), "clipped spread")
        // The whole spread in view → both pages, not split at the fold.
        assertCorners(EdgeDetector.detect(asset("book_spread.jpg")), listOf(120f to 190f, 1500f to 240f, 1470f to 1060f, 90f to 1010f), "full spread")
        // A single page running off the frame keeps its outline up to the frame edge; the long
        // rule inside its margins is not a page edge.
        val q = EdgeDetector.detect(asset("page_rule.jpg"))
        assertNotNull("ruled page: outline should be found", q)
        assertTrue("ruled page must not be cut at the rule: $q", q!!.tr.x > 1150 && q.br.x > 1150)
    }

    @Test
    fun warpAndFilters_produceUprightA4LikePage() {
        val photo = asset("doc_photo.jpg")
        val warped = DocImage.warp(photo, EdgeDetector.detect(photo)!!)
        // The photo is a pinhole projection of an A4 sheet: the true 297/210 aspect is recovered.
        val aspect = warped.height.toFloat() / warped.width
        assertEquals(297f / 210f, aspect, 0.03f)
        FilterType.entries.forEach { f ->
            val out = DocImage.applyFilter(warped, f)
            assertEquals(warped.width, out.width)
        }
        // B&W: paper white, watermark gone (pale grey → white).
        val bw = DocImage.applyFilter(warped, FilterType.BW)
        assertEquals(Color.WHITE, bw.getPixel(bw.width / 2, (bw.height * 0.95f).toInt()))
    }

