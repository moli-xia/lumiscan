// ---------------------------------------------------------------- request / response shapes

@Serializable
data class OcrRequest(
    /** JPEG as base64 (no data: prefix). */
    val image: String,
    val width: Int,
    val height: Int,
    /** "text": plain text; "layout": blocks with type, position and table cells (Word / Excel). */
    val task: String = "text",
)

@Serializable
data class OcrCell(val r0: Int, val r1: Int, val c0: Int, val c1: Int, val text: String)

/** One layout block; coordinates are fractions of the page (0..1). */
@Serializable
data class OcrBlock(
    val type: String,
    val text: String,
    val x0: Double, val y0: Double, val x1: Double, val y1: Double,
    val rows: Int = 0,
    val cols: Int = 0,
    val cells: List<OcrCell> = emptyList(),
)

@Serializable
data class OcrResponse(val text: String = "", val blocks: List<OcrBlock> = emptyList(), val quota: QuotaInfo)

@Serializable
data class DetectRequest(val image: String, val target: String)

@Serializable
data class DetectBox(val x0: Double, val y0: Double, val x1: Double, val y1: Double, val label: String = "")

@Serializable
data class DetectResponse(val boxes: List<DetectBox>, val quota: QuotaInfo)

@Serializable
data class CountRequest(
    val image: String,
    /** What to count, typed by the user (optional, e.g. "钢管"); the model decides when empty. */
    val hint: String = "",
)

/** Object centres as fractions of the image (0..1). */
@Serializable
data class CountPoint(val x: Double, val y: Double)

/** [label] is what the model counted. */
@Serializable
data class CountResponse(val points: List<CountPoint>, val label: String = "", val quota: QuotaInfo)

@Serializable
data class EditOptions(
    /** 证件照: "" keeps the clothes, otherwise "suit_men" / "suit_women" / "shirt_white". */
    val outfit: String = "",
    /** 老照片修复: colourise black-and-white photos. */
    val colorize: Boolean = true,
)

@Serializable
data class EditRequest(
    val feature: String,
    /** JPEG as base64; for "erase" the area to remove is painted solid red by the app. */
    val image: String,
    val width: Int,
    val height: Int,
    val options: EditOptions = EditOptions(),
)

/** [url] is a temporary (24h) download link on Alibaba Cloud OSS. */
@Serializable
data class EditResponse(val url: String, val quota: QuotaInfo)

/** Admin model check: [available] is null when Bailian's model list couldn't be read. */
@Serializable
data class ModelStatus(val setting: String, val label: String, val model: String, val available: Boolean?)

/**
 * 百炼 (DashScope) native API for the image features: qwen OCR, Qwen-VL detection, Qwen-Image
 * editing and Wanx super-resolution. Documents are never re-generated by an image model — for
 * handwriting / watermarks the model only locates the marks and the app removes them from the
 * original pixels, so printed text stays exact.
 */
class VisionGateway(private val s: Services) {
    private val http: HttpClient = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(10)).build()

    private data class Conf(val base: String, val key: String) {
        val compatible get() = base.replace(Regex("/api/v1/?$"), "/compatible-mode/v1")
    }

    private fun conf(): Conf {
        val st = s.settings
        val key = st.get(Settings.DASHSCOPE_API_KEY).trim().ifEmpty { st.get(Settings.AI_API_KEY).trim() }
        if (key.isEmpty()) throw ApiError(503, "ai_not_configured", "AI 服务尚未配置，请联系管理员")
        return Conf(st.get(Settings.DASHSCOPE_BASE_URL).trim().trimEnd('/'), key)
    }

    private fun model(setting: String) = s.settings.get(setting).trim().ifEmpty { Settings.defaults()[setting].orEmpty() }

    /** The model that actually answered (after any fallback); logged with the call. */
    private class Used(var model: String)

    /** Models Bailian reported as missing → when (ms); skipped for an hour instead of failing every call. */
    private val missingModels = java.util.concurrent.ConcurrentHashMap<String, Long>()

    private val UpstreamError.modelMissing: Boolean
        get() = message.orEmpty().let { m ->
            "Model not exist" in m || "model_not_found" in m || "Model.AccessDenied" in m || ("The model" in m && "does not exist" in m)
        }

    /**
     * Calls [block] with the configured [model], then with [fallbacks] when Bailian says the model
     * doesn't exist (Bailian retires models from time to time, e.g. qwen-image-edit on 2026-10-10).
     */
    private suspend fun <R> withFallback(model: String, fallbacks: List<String>, used: Used, block: suspend (String) -> R): R {
        val now = System.currentTimeMillis()
        val chain = (listOf(model) + fallbacks).distinct()
        val live = chain.filter { (missingModels[it] ?: 0L) < now - 3_600_000 }.ifEmpty { chain }
        var last: UpstreamError? = null
        for (m in live) {
            used.model = m
            try {
                return block(m)
            } catch (e: UpstreamError) {
                if (!e.modelMissing) throw e
                missingModels[m] = now
                s.log.warn("Bailian model {} is unavailable ({}); {}", m, e.message, if (m != live.last()) "trying the next one" else "no fallback left")
                last = e
            }
        }
        throw last!!
    }

    // ---------------------------------------------------------------- endpoints

    suspend fun ocr(u: UserRow, req: OcrRequest, ip: String): OcrResponse {
        checkImage(req.image)
        val model = model(Settings.OCR_MODEL)
        return run(u, Feature.OCR, model, ip) { q, used ->
            withFallback(model, OCR_FALLBACKS, used) { m ->
                when (req.task) {
                    "layout" -> {
                        val (blocks, tokens) = ocrLayout(m, req)
                        Triple(OcrResponse(blocks = blocks, quota = q), tokens.first, tokens.second)
                    }
                    else -> {
                        val c = chat(conf().compatible, m, req.image, OCR_TEXT_PROMPT, 8000)
                        Triple(OcrResponse(text = markdownToText(c.content), quota = q), c.promptTokens, c.completionTokens)
                    }
                }
            }
        }
    }

    suspend fun detect(u: UserRow, req: DetectRequest, ip: String): DetectResponse {
        checkImage(req.image)
        val (feature, prompt) = when (req.target) {
            "handwriting" -> Feature.HANDWRITING to DETECT_HANDWRITING
            "watermark" -> Feature.WATERMARK to DETECT_WATERMARK
            else -> throw bad("未知的识别目标")
        }
        val model = model(Settings.DETECT_MODEL)
        return run(u, feature, model, ip) { q, used ->
            val c = withFallback(model, DETECT_FALLBACKS, used) { m -> chat(conf().compatible, m, req.image, prompt, 2000) }
            Triple(DetectResponse(parseBoxes(c.content), q), c.promptTokens, c.completionTokens)
        }
    }

    /** 拍照计数: the model marks the centre of every object; the app shows and edits the marks. */
    suspend fun count(u: UserRow, req: CountRequest, ip: String): CountResponse {
        checkImage(req.image)
        val model = model(Settings.DETECT_MODEL)
        val prompt = countPrompt(req.hint)
        return run(u, Feature.COUNT, model, ip) { q, used ->
            // Hundreds of points take a while to write out.
            val c = withFallback(model, DETECT_FALLBACKS, used) { m -> chat(conf().compatible, m, req.image, prompt, 8000, timeoutSec = 180) }
            val (label, points) = parsePoints(c.content)
            Triple(CountResponse(points, label, q), c.promptTokens, c.completionTokens)
        }
    }

    suspend fun edit(u: UserRow, req: EditRequest, ip: String): EditResponse {
        checkImage(req.image)
        if (req.width < 64 || req.height < 64) throw bad("图片太小")
        val feature = Feature.of(req.feature)?.takeIf { it in setOf(Feature.ID_PHOTO, Feature.RESTORE, Feature.ERASE, Feature.UPSCALE) }
            ?: throw bad("未知的图像功能")
        val model = when (feature) {
            Feature.UPSCALE -> model(Settings.UPSCALE_MODEL)
            Feature.RESTORE -> model(Settings.RESTORE_MODEL)
            Feature.ID_PHOTO -> model(Settings.IDPHOTO_MODEL)
            else -> model(Settings.EDIT_MODEL)
        }
        val size = outputSize(req.width, req.height)
        return run(u, feature, model, ip) { q, used ->
            val url = when (feature) {
                Feature.UPSCALE -> wanxSuperResolution(model, req.image)
                Feature.ID_PHOTO -> withFallback(model, IDPHOTO_FALLBACKS, used) { m -> qwenEdit(m, req.image, idPhotoPrompt(req.options.outfit), size) }
                Feature.RESTORE -> withFallback(model, IMAGE_FALLBACKS, used) { m -> qwenEdit(m, req.image, restorePrompt(req.options.colorize), size) }
                else -> withFallback(model, IMAGE_FALLBACKS, used) { m -> qwenEdit(m, req.image, ERASE_PROMPT, size) }
            }
            Triple(EditResponse(url, q), 0L, 0L)
        }
    }

    // ---------------------------------------------------------------- quota + logging around a call

    private suspend fun <T> run(
        u: UserRow, feature: Feature, model: String, ip: String,
        call: suspend (QuotaInfo, Used) -> Triple<T, Long, Long>,
    ): T {
        val lim = s.limits(u)
        if (feature.key !in lim.features) {
            s.logAi(u.id, feature, model, 0, 0, 0, "rejected", "feature disabled", 0, ip)
            throw ApiError(403, "feature_disabled", "当前账号分组（${lim.group.name}）未开通「${feature.label}」")
        }
        conf() // fail fast when unconfigured, before counting the call
        return s.userSlot(u.id) {
            try {
                s.reserveRequest(u, lim, feature.kind)
            } catch (e: ApiError) {
                s.logAi(u.id, feature, model, 0, 0, 0, "rejected", e.message, 0, ip)
                throw e
            }
            val started = System.currentTimeMillis()
            val used = Used(model)
            try {
                // The quota passed in already reflects this call.
                val (result, prompt, completion) = call(s.quotaInfo(u, lim), used)
                s.logAi(u.id, feature, used.model, prompt, completion, 0, "ok", null, (System.currentTimeMillis() - started).toInt(), ip)
                result
            } catch (e: Throwable) {
                s.refundRequest(u.id, feature.kind)
                s.logAi(u.id, feature, used.model, 0, 0, 0, "error", e.message ?: e.javaClass.simpleName, (System.currentTimeMillis() - started).toInt(), ip)
                s.log.warn("{} failed for user {}: {}", feature.key, u.id, e.message)
                throw when (e) {
                    is ApiError -> e
                    is java.net.http.HttpTimeoutException -> ApiError(504, "ai_timeout", "AI 处理超时，请稍后重试")
                    is UpstreamError -> ApiError(502, "ai_failed", "AI 服务暂时不可用（${e.status}），请稍后再试")
                    else -> ApiError(502, "ai_failed", "AI 服务暂时不可用，请稍后再试")
                }
            }
        }
    }

    private fun checkImage(b64: String) {
        if (b64.isBlank()) throw bad("请上传图片")
        if (b64.length > MAX_IMAGE_B64) throw bad("图片过大，请压缩后再试")
    }

    // ---------------------------------------------------------------- model calls

    private suspend fun send(url: String, body: JsonObject, timeoutSec: Long, async: Boolean = false): JsonObject = withContext(Dispatchers.IO) {
        val c = conf()
        val b = HttpRequest.newBuilder(URI.create(url))
            .timeout(Duration.ofSeconds(timeoutSec))
            .header("Authorization", "Bearer ${c.key}")
            .header("Content-Type", "application/json")
        if (async) b.header("X-DashScope-Async", "enable")
        parse(http.sendRetrying(b.POST(HttpRequest.BodyPublishers.ofString(body.toString())).build()))
    }

    private suspend fun getJson(url: String): JsonObject = withContext(Dispatchers.IO) {
        val req = HttpRequest.newBuilder(URI.create(url)).timeout(Duration.ofSeconds(30)).header("Authorization", "Bearer ${conf().key}").GET().build()
        parse(http.sendRetrying(req))
    }

    private fun parse(resp: HttpResponse<String>): JsonObject {
        val json = runCatching { AppJson.parseToJsonElement(resp.body()).jsonObject }.getOrNull()
        if (resp.statusCode() !in 200..299 || json == null) {
            val err = json?.get("error") as? JsonObject
            val code = ((json?.get("code") ?: err?.get("code")) as? JsonPrimitive)?.contentOrNull.orEmpty()
            val text = ((json?.get("message") ?: err?.get("message")) as? JsonPrimitive)?.contentOrNull
            val msg = text?.let { if (code.isNotEmpty() && code !in it) "$code: $it" else it } ?: resp.body().take(200)
            throw UpstreamError(resp.statusCode(), msg)
        }
        return json
    }

    private class Chat(val content: String, val promptTokens: Long, val completionTokens: Long)

    /** OpenAI-compatible chat with one image (OCR text, detection). */
    private suspend fun chat(base: String, model: String, imageB64: String, prompt: String, maxTokens: Int, timeoutSec: Long = 120): Chat {
        val body = buildJsonObject {
            put("model", model)
            putJsonArray("messages") {
                addJsonObject {
                    put("role", "user")
                    putJsonArray("content") {
                        addJsonObject { put("type", "image_url"); putJsonObject("image_url") { put("url", "data:image/jpeg;base64,$imageB64") } }
                        addJsonObject { put("type", "text"); put("text", prompt) }
                    }
                }
            }
            put("max_tokens", maxTokens)
            put("temperature", 0.01)
        }
        val json = send("$base/chat/completions", body, timeoutSec)
        val content = json["choices"]?.jsonArray?.firstOrNull()?.jsonObject?.get("message")?.jsonObject?.get("content")
        val text = when (content) {
            is JsonPrimitive -> content.contentOrNull.orEmpty()
            is JsonArray -> content.joinToString("") { (it as? JsonObject)?.get("text")?.jsonPrimitive?.contentOrNull.orEmpty() }
            else -> throw UpstreamError(200, "响应中没有内容")
        }
        val usage = json["usage"] as? JsonObject
        return Chat(text, usage.long("prompt_tokens"), usage.long("completion_tokens"))
    }

    /** qwen OCR document parsing: titles, paragraphs and tables with merged cells. */
    private suspend fun ocrLayout(model: String, req: OcrRequest): Pair<List<OcrBlock>, Pair<Long, Long>> {
        val body = buildJsonObject {
            put("model", model)
            putJsonObject("input") {
                putJsonArray("messages") {
                    addJsonObject {
                        put("role", "user")
                        putJsonArray("content") { addJsonObject { put("image", "data:image/jpeg;base64,${req.image}") } }
                    }
                }
            }
            putJsonObject("parameters") { putJsonObject("ocr_options") { put("task", "document_parsing") } }
        }
        val json = send("${conf().base}/services/aigc/multimodal-generation/generation", body, 150)
        val usage = json["usage"] as? JsonObject
        val content = json["output"]?.jsonObject?.get("choices")?.jsonArray?.firstOrNull()?.jsonObject
            ?.get("message")?.jsonObject?.get("content")?.jsonArray?.firstOrNull()?.jsonObject
            ?: throw UpstreamError(200, "响应中没有识别结果")
        val layouts = (content["ocr_result"] as? JsonObject)?.get("layouts") as? JsonArray ?: JsonArray(emptyList())
        val w = req.width.coerceAtLeast(1).toDouble()
        val h = req.height.coerceAtLeast(1).toDouble()
        val seen = HashSet<String>()
        val blocks = layouts.mapNotNull { el ->
            val l = el as? JsonObject ?: return@mapNotNull null
            val id = l.str("uniqueId")
            if (id.isNotEmpty() && !seen.add(id)) return@mapNotNull null // the API repeats layouts
            val pts = (l["pos"] as? JsonArray)?.mapNotNull { p -> (p as? JsonObject)?.let { it.num("x") to it.num("y") } }.orEmpty()
            val type = l.str("type").ifEmpty { "text" }
            val box = if (pts.isEmpty()) doubleArrayOf(0.0, 0.0, 1.0, 1.0) else doubleArrayOf(
                pts.minOf { it.first } / w, pts.minOf { it.second } / h, pts.maxOf { it.first } / w, pts.maxOf { it.second } / h,
            )
            val cells = if (type == "table") (l["cells"] as? JsonArray).orEmpty().mapNotNull { ce ->
                val c = ce as? JsonObject ?: return@mapNotNull null
                val text = (c["layouts"] as? JsonArray).orEmpty().joinToString("\n") { (it as? JsonObject)?.str("text").orEmpty().trim() }.trim()
                OcrCell(c.int("ysc"), c.int("yec"), c.int("xsc"), c.int("xec"), text)
            } else emptyList()
            OcrBlock(
                type = type,
                text = l.str("text").trim().ifEmpty { markdownToText(l.str("markdownContent")) },
                x0 = box[0].coerceIn(0.0, 1.0), y0 = box[1].coerceIn(0.0, 1.0), x1 = box[2].coerceIn(0.0, 1.0), y1 = box[3].coerceIn(0.0, 1.0),
                rows = l.int("numRow").takeIf { it > 0 } ?: ((cells.maxOfOrNull { it.r1 } ?: -1) + 1),
                cols = l.int("numCol").takeIf { it > 0 } ?: ((cells.maxOfOrNull { it.c1 } ?: -1) + 1),
                cells = cells,
            )
        }
        return blocks to (usage.long("input_tokens") to usage.long("output_tokens"))
    }

    /** Qwen-Image editing (synchronous); returns the result URL. */
    private suspend fun qwenEdit(model: String, imageB64: String, prompt: String, size: String): String {
        val body = buildJsonObject {
            put("model", model)
            putJsonObject("input") {
                putJsonArray("messages") {
                    addJsonObject {
                        put("role", "user")
                        putJsonArray("content") {
                            addJsonObject { put("image", "data:image/jpeg;base64,$imageB64") }
                            addJsonObject { put("text", prompt) }
                        }
                    }
                }
            }
            putJsonObject("parameters") {
                put("n", 1)
                put("size", size)
                put("watermark", false)
                put("prompt_extend", false)
                put("negative_prompt", "边框，相框，文字水印，模糊，变形，多余的手指")
            }
        }
        val json = send("${conf().base}/services/aigc/multimodal-generation/generation", body, 150)
        return json["output"]?.jsonObject?.get("choices")?.jsonArray?.firstOrNull()?.jsonObject
            ?.get("message")?.jsonObject?.get("content")?.jsonArray
            ?.firstNotNullOfOrNull { (it as? JsonObject)?.str("image")?.takeIf { u -> u.isNotEmpty() } }
            ?: throw UpstreamError(200, "响应中没有图片")
    }

    /** Wanx super-resolution: an async task that is polled until done (≈20–40 s). */
    private suspend fun wanxSuperResolution(model: String, imageB64: String): String {
        val body = buildJsonObject {
            put("model", model)
            putJsonObject("input") {
                put("function", "super_resolution")
                put("prompt", "图像超分，提升清晰度和细节")
                put("base_image_url", "data:image/jpeg;base64,$imageB64")
            }
            putJsonObject("parameters") { put("n", 1); put("upscale_factor", 2) }
        }
        val base = conf().base
        val created = send("$base/services/aigc/image2image/image-synthesis", body, 60, async = true)
        val taskId = created["output"]?.jsonObject?.str("task_id")?.takeIf { it.isNotEmpty() } ?: throw UpstreamError(200, "没有返回任务")
        val deadline = System.currentTimeMillis() + 150_000
        while (System.currentTimeMillis() < deadline) {
            delay(2500)
            val out = getJson("$base/tasks/$taskId")["output"]?.jsonObject ?: continue
            when (out.str("task_status")) {
                "SUCCEEDED" -> return (out["results"] as? JsonArray)?.firstNotNullOfOrNull { (it as? JsonObject)?.str("url")?.takeIf { u -> u.isNotEmpty() } }
                    ?: throw UpstreamError(200, out["results"].toString().take(200))
                "FAILED", "CANCELED", "UNKNOWN" -> throw UpstreamError(200, out.str("message").ifEmpty { out.str("code") })
            }
        }
        throw java.net.http.HttpTimeoutException("super resolution timed out")
    }

