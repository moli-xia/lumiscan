        /** Output size keeping the aspect ratio: sides within 512–2048, multiples of 16. */
        fun outputSize(w: Int, h: Int): String {
            var scale = min(2048.0 / max(w, h), 1.0)
            if (min(w, h) * scale < 512) scale = 512.0 / min(w, h)
            val ow = ((w * scale / 16).roundToInt() * 16).coerceIn(512, 2048)
            val oh = ((h * scale / 16).roundToInt() * 16).coerceIn(512, 2048)
            return "$ow*$oh"
        }

        /** Markdown (tables included) → plain text: table rows become tab-separated lines. */
        fun markdownToText(md: String): String = md.lines().mapNotNull { raw ->
            val line = raw.trimEnd()
            when {
                Regex("^\\s*\\|?\\s*:?-{3,}").containsMatchIn(line) && line.replace(Regex("[|:\\-\\s]"), "").isEmpty() -> null
                line.trimStart().startsWith("|") -> line.trim().trim('|').split("|").joinToString("\t") { it.trim() }
                else -> line.replace(Regex("^#{1,6}\\s+"), "").replace(Regex("<[^>]+>"), "")
            }
        }.joinToString("\n").replace(Regex("\n{3,}"), "\n\n").trim()

        /**
         * Parses `{"label": …, "points": [[x, y], …]}` (0–1000) from a model reply; also accepts the
         * model's native `[{"point_2d": [x, y]}, …]` and box centres. Duplicate points are dropped.
         */
        fun parsePoints(reply: String): Pair<String, List<CountPoint>> {
            val start = listOf(reply.indexOf('{'), reply.indexOf('[')).filter { it >= 0 }.minOrNull() ?: return "" to emptyList()
            val end = maxOf(reply.lastIndexOf('}'), reply.lastIndexOf(']'))
            if (end <= start) return "" to emptyList()
            val root = runCatching { AppJson.parseToJsonElement(reply.substring(start, end + 1)) }.getOrNull()
            var label = ""
            val raw = ArrayList<List<Double>>()
            fun nums(e: JsonElement?) = (e as? JsonArray)?.mapNotNull { (it as? JsonPrimitive)?.doubleOrNull }
            fun take(e: JsonElement?) {
                when (e) {
                    is JsonArray -> {
                        val v = nums(e)
                        if (v != null && v.size == 2 && e.size == 2) raw += v else e.forEach { take(it) }
                    }
                    is JsonObject -> {
                        if (label.isEmpty()) label = (e["label"] as? JsonPrimitive)?.contentOrNull.orEmpty()
                        nums(e["point_2d"] ?: e["point"])?.takeIf { it.size == 2 }?.let(raw::add)
                        nums(e["bbox_2d"] ?: e["bbox"])?.takeIf { it.size == 4 }?.let { raw += listOf((it[0] + it[2]) / 2, (it[1] + it[3]) / 2) }
                        take(e["points"])
                    }
                    else -> Unit
                }
            }
            if (root != null) {
                take(root)
            } else {
                // Cut off mid-list (output limit): keep every complete pair.
                Regex("\\[\\s*(-?\\d+(?:\\.\\d+)?)\\s*,\\s*(-?\\d+(?:\\.\\d+)?)\\s*]").findAll(reply).forEach { m ->
                    raw += listOf(m.groupValues[1].toDouble(), m.groupValues[2].toDouble())
                }
                label = Regex("\"label\"\\s*:\\s*\"([^\"]*)\"").find(reply)?.groupValues?.get(1).orEmpty()
            }
            val out = ArrayList<CountPoint>()
            for ((x, y) in raw) {
                val p = CountPoint((x / 1000).coerceIn(0.0, 1.0), (y / 1000).coerceIn(0.0, 1.0))
                if (out.none { kotlin.math.abs(it.x - p.x) < 0.002 && kotlin.math.abs(it.y - p.y) < 0.002 }) out += p
            }
            return label.take(30) to out
        }

        /** Parses `[{"bbox_2d":[x1,y1,x2,y2],"label":…}]` (0–1000) from a model reply. */
        fun parseBoxes(reply: String): List<DetectBox> {
            val start = reply.indexOf('[')
            val end = reply.lastIndexOf(']')
            if (start < 0 || end <= start) return emptyList()
            val arr = runCatching { AppJson.parseToJsonElement(reply.substring(start, end + 1)).jsonArray }.getOrNull() ?: return emptyList()
            return arr.mapNotNull { el ->
                val o = el as? JsonObject ?: return@mapNotNull null
                val b = (o["bbox_2d"] ?: o["bbox"]) as? JsonArray ?: return@mapNotNull null
                val v = b.mapNotNull { (it as? JsonPrimitive)?.doubleOrNull }
                if (v.size != 4) return@mapNotNull null
                val x0 = min(v[0], v[2]) / 1000; val x1 = max(v[0], v[2]) / 1000
                val y0 = min(v[1], v[3]) / 1000; val y1 = max(v[1], v[3]) / 1000
                if (x1 - x0 < 0.002 || y1 - y0 < 0.002) return@mapNotNull null
                DetectBox(x0.coerceIn(0.0, 1.0), y0.coerceIn(0.0, 1.0), x1.coerceIn(0.0, 1.0), y1.coerceIn(0.0, 1.0), (o["label"] as? JsonPrimitive)?.contentOrNull.orEmpty().take(60))
            }
        }
