    @Volatile private var modelList: Pair<Long, Set<String>>? = null

    /** Every model the key can call, from Bailian's (free) model list; cached for 30 minutes. */
    private suspend fun availableModels(force: Boolean): Set<String> {
        modelList?.let { (at, ids) -> if (!force && System.currentTimeMillis() - at < 30 * 60_000) return ids }
        val ids = HashSet<String>()
        var page = 1
        while (page <= 20) {
            val out = getJson("${conf().base}/models?page_no=$page&page_size=100")["output"] as? JsonObject ?: break
            val models = (out["models"] as? JsonArray).orEmpty()
            models.forEach { m -> (m as? JsonObject)?.let { o -> o.str("model").ifEmpty { o.str("name") }.takeIf { it.isNotEmpty() }?.let(ids::add) } }
            if (models.size < 100 || ids.size >= out.int("total")) break
            page++
        }
        if (ids.isEmpty()) throw UpstreamError(200, "模型列表为空")
        modelList = System.currentTimeMillis() to ids
        return ids
    }

    /**
     * Whether each configured model still exists on Bailian (models are retired from time to time).
     * The chat models are only checked when they also go to Bailian.
     */
    suspend fun checkModels(force: Boolean = false): List<ModelStatus> {
        val st = s.settings
        val checks = buildList {
            if ("dashscope" in st.get(Settings.AI_BASE_URL)) {
                add(Triple(Settings.AI_TEXT_MODEL, "文本模型", model(Settings.AI_TEXT_MODEL)))
                add(Triple(Settings.AI_VISION_MODEL, "视觉模型（拍题）", model(Settings.AI_VISION_MODEL)))
            }
            add(Triple(Settings.OCR_MODEL, "文字识别", model(Settings.OCR_MODEL)))
            add(Triple(Settings.DETECT_MODEL, "笔迹/水印定位、计数", model(Settings.DETECT_MODEL)))
            add(Triple(Settings.IDPHOTO_MODEL, "证件照", model(Settings.IDPHOTO_MODEL)))
            add(Triple(Settings.EDIT_MODEL, "智能消除", model(Settings.EDIT_MODEL)))
            add(Triple(Settings.RESTORE_MODEL, "老照片修复", model(Settings.RESTORE_MODEL)))
            add(Triple(Settings.UPSCALE_MODEL, "图片变清晰", model(Settings.UPSCALE_MODEL)))
        }
        val ids = runCatching { availableModels(force) }.onFailure { s.log.warn("model list unavailable: {}", it.message) }.getOrNull()
        return checks.map { (key, label, m) -> ModelStatus(key, label, m, ids?.contains(m)) }
    }

    companion object {
        const val MAX_IMAGE_B64 = 7_000_000

        // Tried in order when the configured model has been retired.
        val OCR_FALLBACKS = listOf("qwen3.5-ocr", "qwen-vl-ocr-latest")
        val DETECT_FALLBACKS = listOf("qwen3-vl-plus", "qwen3-vl-flash")
        val IDPHOTO_FALLBACKS = listOf("qwen-image-3.0-pro", "qwen-image-3.0")
        val IMAGE_FALLBACKS = listOf("qwen-image-3.0", "qwen-image-3.0-pro")

