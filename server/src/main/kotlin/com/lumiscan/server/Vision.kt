private fun JsonObject?.long(k: String): Long = (this?.get(k) as? JsonPrimitive)?.longOrNull ?: 0L
private fun JsonObject.str(k: String): String = (this[k] as? JsonPrimitive)?.contentOrNull.orEmpty()
private fun JsonObject.int(k: String): Int = (this[k] as? JsonPrimitive)?.intOrNull ?: 0
private fun JsonObject.num(k: String): Double = (this[k] as? JsonPrimitive)?.doubleOrNull ?: 0.0
private fun JsonArray?.orEmpty(): List<JsonElement> = this ?: emptyList()
